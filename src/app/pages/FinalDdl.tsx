// 최종 DDL 검토: 이 버전의 schema.sql을 테이블별로 나눠, 이전 버전에서 바뀐 부분과 회사 설계 표준 준수 여부를 함께 보여준다.
// 설계 표준의 기준은 백엔드 req_agent/tools/model_validator.py의 검사이고, 그 결과(이슈)를 그대로 쓴다.
// 감사 컬럼·snake_case는 백엔드가 자동으로 맞추는 규칙이라 이슈가 없으므로 화면에서 확인한다.

interface Rule {
  id: string
  label: string
  kinds: string[]                       // 이 규칙을 어기면 백엔드가 남기는 이슈 종류
  check?: (e: Entity) => string | null  // 화면에서 확인하는 규칙 (위반 내용, 없으면 통과)
}

const SNAKE = /^[a-z][a-z0-9_]*$/

const RULES: Rule[] = [
  { id: 'pk', label: '기본키는 단일 대리키 <테이블>_id (bigint)', kinds: ['MODEL_NO_PK', 'MODEL_PK_STANDARD'] },
  { id: 'fk', label: '외래키 이름은 _id로 끝남', kinds: ['MODEL_FK_NAMING'] },
  { id: 'target', label: '외래키가 있는 테이블의 단일 기본키를 참조', kinds: ['MODEL_FK_TARGET_MISSING', 'MODEL_FK_COMPOSITE_TARGET'] },
  { id: 'parent', label: '정해진 상위 테이블을 외래키로 참조', kinds: ['MODEL_PARENT_NOT_REFERENCED'] },
  { id: 'secret', label: '인증 정보(비밀번호·토큰 등)를 평문으로 저장하지 않음', kinds: ['MODEL_PLAINTEXT_SECRET'] },
  { id: 'reserved', label: 'PostgreSQL 예약어를 이름으로 쓰지 않음', kinds: ['MODEL_RESERVED_WORD'] },
  {
    id: 'audit', label: '감사 컬럼 created_at·updated_at', kinds: [],
    check: (e) => {
      const missing = ['created_at', 'updated_at'].filter((c) => !e.attributes.some((a) => a.name === c))
      return missing.length ? `${missing.join(', ')} 없음` : null
    },
  },
  {
    id: 'snake', label: '테이블·컬럼 이름은 snake_case', kinds: [],
    check: (e) => {
      const bad = [e.entity_id, ...e.attributes.map((a) => a.name)].filter((n) => !SNAKE.test(n))
      return bad.length ? `${bad.slice(0, 3).join(', ')}${bad.length > 3 ? ` 외 ${bad.length - 3}개` : ''}` : null
    },
  },
]

type Change = 'added' | 'changed' | 'removed' | 'same'

interface ColumnDiff { name: string; kind: 'added' | 'removed' | 'changed'; detail: string }

interface TableReview {
  id: string
  label: string
  entity?: Entity
  change: Change
  columns: ColumnDiff[]
  by: ('user' | 'agent')[]
  rules: { rule: Rule; problem: string | null; severity?: Issue['severity'] }[]
  ddl: string[]
}

const colSig = (a: Attribute) => ({
  type: `${a.data_type}${a.length ? `(${a.length})` : ''}`,
  keys: [a.primary_key && 'PK', a.unique && 'UK', a.references && `FK→${a.references}`, !a.nullable && 'NOT NULL'].filter(Boolean).join(' '),
})

function diffColumns(before: Entity | undefined, after: Entity | undefined): ColumnDiff[] {
  const b = new Map((before?.attributes ?? []).map((a) => [a.name, a]))
  const a = new Map((after?.attributes ?? []).map((x) => [x.name, x]))
  const out: ColumnDiff[] = []
  for (const [name, col] of a) {
    const old = b.get(name)
    if (!old) { out.push({ name, kind: 'added', detail: `${colSig(col).type} ${colSig(col).keys}`.trim() }); continue }
    const x = colSig(old)
    const y = colSig(col)
    const parts = [x.type !== y.type && `${x.type} → ${y.type}`, x.keys !== y.keys && `${x.keys || '없음'} → ${y.keys || '없음'}`,
      old.label !== col.label && `이름 ${old.label} → ${col.label}`].filter(Boolean)
    if (parts.length) out.push({ name, kind: 'changed', detail: parts.join(', ') })
  }
  for (const [name, col] of b) if (!a.has(name)) out.push({ name, kind: 'removed', detail: colSig(col).type })
  return out
}

/** schema.sql을 테이블별 문장으로 나눈다 (CREATE TABLE · COMMENT · ALTER · INDEX) */
function splitDdl(sql: string): Map<string, string[]> {
  const blocks = new Map<string, string[]>()
  for (const raw of sql.split(/\n\s*\n/)) {
    // 파일 맨 앞 머리 주석(-- Generated by …)이 첫 테이블 문장에 붙어 있으므로 앞쪽 주석 줄은 뗀다
    const stmt = raw.replace(/^(\s*--[^\n]*\n)+/, '')
    const m = /CREATE TABLE\s+"?(\w+)"?|COMMENT ON TABLE\s+"?(\w+)"?|COMMENT ON COLUMN\s+"?(\w+)"?\.|ALTER TABLE\s+"?(\w+)"?|CREATE (?:UNIQUE )?INDEX\s+\S+\s+ON\s+"?(\w+)"?/i.exec(stmt)
    const table = m?.slice(1).find(Boolean)
    if (!table) continue
    blocks.set(table, [...(blocks.get(table) ?? []), stmt.trim()])
  }
  return blocks
}

export function FinalDdlReview({ design, project, version, versions }: {
  design: Design            // 이 버전에 저장된 설계 (화면 편집 전)
  project: string
  version: string
  versions: VersionRecord[]
}) {
  const record = versions.find((v) => v.design_version === version)
  const parent = record?.parent ?? null
  const [parentDesign, setParentDesign] = useState<Design | null | 'loading'>(parent ? 'loading' : null)
  const sql = useFile(project, version, 'schema.sql')
  const [filter, setFilter] = useState<'all' | 'changed' | 'violations'>('changed')
  const [query, setQuery] = useState('')
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    if (!parent) { setParentDesign(null); return }
    let cancelled = false
    setParentDesign('loading')
    getDesign(project, parent).then((d) => { if (!cancelled) setParentDesign(d) }).catch(() => { if (!cancelled) setParentDesign(null) })
    return () => { cancelled = true }
  }, [project, parent])

  const rework = (design.meta as { rework?: { edited?: string[]; added?: string[]; redesigned?: string[] } }).rework

  const tables = useMemo<TableReview[] | null>(() => {
    if (parentDesign === 'loading' || sql.state !== 'ready') return null
    const blocks = splitDdl(sql.data ?? '')
    const now = design.data_model.entities
    const before = parentDesign?.data_model.entities ?? []
    const hasBase = Boolean(parentDesign && before.length)
    const open = design.issues.filter((i) => i.status !== 'RESOLVED')
    const rows: TableReview[] = now.map((e) => {
      const old = before.find((b) => b.entity_id === e.entity_id)
      const columns = hasBase ? diffColumns(old, e) : []
      const change: Change = !hasBase ? 'same' : !old ? 'added' : columns.length || old.label !== e.label ? 'changed' : 'same'
      const by: ('user' | 'agent')[] = [
        ...(rework?.edited?.includes(e.entity_id) || rework?.added?.includes(e.entity_id) || e.user_edited ? ['user' as const] : []),
        ...(rework?.redesigned?.includes(e.entity_id) ? ['agent' as const] : []),
      ]
      const rules = RULES.map((rule) => {
        const issue = open.find((i) => rule.kinds.includes(i.kind) && i.target_id.split(/,\s*/).includes(e.entity_id))
        if (issue) return { rule, problem: issue.message.replace(new RegExp(`^${e.entity_id}:\\s*`), ''), severity: issue.severity }
        const problem = rule.check?.(e) ?? null
        return { rule, problem, severity: problem ? 'WARNING' as const : undefined }
      })
      return { id: e.entity_id, label: e.label, entity: e, change, columns, by, rules, ddl: blocks.get(e.entity_id) ?? [] }
    })
    const removed: TableReview[] = hasBase
      ? before.filter((b) => !now.some((e) => e.entity_id === b.entity_id)).map((b) => ({
          id: b.entity_id, label: b.label, change: 'removed', columns: diffColumns(b, undefined), by: [], rules: [], ddl: [],
        }))
      : []
    return [...rows, ...removed]
  }, [design, parentDesign, sql, rework])

  if (sql.state === 'loading' || !tables) return <Loading label="최종 DDL과 이전 버전을 불러오는 중" lines={8} />
  if (sql.state === 'error') return <ErrorNote message={sql.message} />
  if (sql.data === null) return <Empty title="이 버전에는 schema.sql 파일이 없습니다">ERD 단계에서 만든 버전(v2.1 …)을 열어 보세요.</Empty>

  const hasBase = parentDesign !== null && parentDesign !== 'loading' && parentDesign.data_model.entities.length > 0
  const changed = tables.filter((t) => t.change !== 'same')
  const violating = tables.filter((t) => t.rules.some((r) => r.problem))
  const errors = tables.reduce((n, t) => n + t.rules.filter((r) => r.problem && r.severity === 'ERROR').length, 0)
  const q = query.trim().toLowerCase()
  const shown = (filter === 'changed' ? changed : filter === 'violations' ? violating : tables)
    .filter((t) => !q || t.id.includes(q) || t.label.toLowerCase().includes(q))
  const text = sql.data

  return (
    <div className="space-y-5">
      <dl className="grid gap-2 sm:grid-cols-4">
        <Stat term="테이블" value={fmt(design.data_model.entities.length)} note={`v${version}`} />
        <Stat term="바뀐 테이블" value={hasBase ? fmt(changed.length) : '—'} note={hasBase ? `비교: v${parent}` : '비교할 이전 ERD 없음'} />
        <Stat term="표준 위반 테이블" value={fmt(violating.length)} note={`오류 ${errors} · 경고 ${violating.reduce((n, t) => n + t.rules.filter((r) => r.problem && r.severity !== 'ERROR').length, 0)}`} tone={errors ? 'danger' : violating.length ? 'warn' : 'ok'} />
        <Stat term="DDL" value={`${fmt(text.split('\n').length)}줄`} note="PostgreSQL" />
      </dl>

      <div className="flex flex-wrap items-center gap-3">
        <Segmented
          label="테이블 고르기"
          value={filter}
          onChange={setFilter}
          options={[
            { value: 'changed', label: '바뀐 테이블', count: changed.length },
            { value: 'violations', label: '표준 위반', count: violating.length },
            { value: 'all', label: '전체', count: tables.length },
          ]}
        />
        <div className="relative w-full sm:w-56">
          <MagnifyingGlass size={16} className="pointer-events-none absolute top-1/2 left-3 -translate-y-1/2 text-fg-3" aria-hidden="true" />
          <TextInput dense type="search" aria-label="테이블 검색" placeholder="테이블 검색" value={query} onChange={(e) => setQuery(e.target.value)} className="pl-9" />
        </div>
        <div className="ml-auto flex gap-2">
          <Button size="sm" icon={copied ? <Check /> : <Copy />} onClick={() => navigator.clipboard?.writeText(text).then(() => { setCopied(true); window.setTimeout(() => setCopied(false), 1500) })}>
            {copied ? '복사함' : '전체 DDL 복사'}
          </Button>
          <a href={fileUrl(project, version, 'schema.sql')} download={`schema.v${version}.sql`}
            className="inline-flex min-h-8 items-center gap-1.5 rounded-sm border border-line-strong bg-card px-2.5 text-small font-semibold hover:border-control hover:bg-sunken">
            <DownloadSimple size={16} aria-hidden="true" />받기
          </a>
        </div>
      </div>

      {shown.length === 0 ? (
        <Empty title={filter === 'changed' ? (hasBase ? '이전 버전과 같은 테이블뿐입니다' : '비교할 이전 ERD가 없습니다') : filter === 'violations' ? '설계 표준을 어긴 테이블이 없습니다' : '테이블이 없습니다'}>
          {filter !== 'all' && "'전체'를 누르면 모든 테이블의 DDL과 표준 검사를 볼 수 있습니다."}
        </Empty>
      ) : (
        <ul className="space-y-3">
          {shown.map((t) => <TableCard key={t.id} t={t} />)}
        </ul>
      )}
    </div>
  )
}

function Stat({ term, value, note, tone }: { term: string; value: string; note?: string; tone?: 'ok' | 'warn' | 'danger' }) {
  return (
    <div className="rounded-lg border border-line px-3 py-2.5">
      <dt className="text-small text-fg-3">{term}</dt>
      <dd className={cx('mt-0.5 text-subtitle font-medium tabular-nums', tone === 'danger' && 'text-danger', tone === 'warn' && 'text-warn', tone === 'ok' && 'text-ok')}>{value}</dd>
      {note && <dd className="text-micro text-fg-3">{note}</dd>}
    </div>
  )
}

const CHANGE_BADGE: Record<Change, { tone: 'ok' | 'warn' | 'danger' | 'neutral'; label: string }> = {
  added: { tone: 'ok', label: '추가' },
  changed: { tone: 'warn', label: '수정' },
  removed: { tone: 'danger', label: '삭제' },
  same: { tone: 'neutral', label: '변경 없음' },
}

function TableCard({ t }: { t: TableReview }) {
  const [open, setOpen] = useState(t.change !== 'same' || t.rules.some((r) => r.problem))
  const problems = t.rules.filter((r) => r.problem)
  const changedCols = new Map(t.columns.map((c) => [c.name, c.kind]))
  const badge = CHANGE_BADGE[t.change]

  return (
    <li className="rounded-lg border border-line">
      <button
        type="button"
        aria-expanded={open}
        onClick={() => setOpen(!open)}
        className="flex w-full flex-wrap items-center gap-2 rounded-lg px-4 py-3 text-left transition-colors duration-150 hover:bg-sunken"
      >
        <span className="font-mono text-label font-medium">{t.id}</span>
        <span className="text-small text-fg-3">{t.label}</span>
        <span className="ml-auto flex flex-wrap gap-1">
          <Badge tone={badge.tone}>{badge.label}</Badge>
          {t.by.includes('user') && <Badge tone="info">사용자 수정</Badge>}
          {t.by.includes('agent') && <Badge>Agent 재설계</Badge>}
          {t.change !== 'removed' && (problems.length
            ? <Badge tone={problems.some((p) => p.severity === 'ERROR') ? 'danger' : 'warn'} icon={<Warning weight="bold" aria-hidden="true" />}>표준 위반 {problems.length}</Badge>
            : <Badge tone="ok" icon={<CheckCircle weight="fill" aria-hidden="true" />}>표준 준수</Badge>)}
        </span>
      </button>

      {open && (
        <div className="grid gap-4 border-t border-line px-4 py-4 lg:grid-cols-[minmax(0,1fr)_minmax(0,1.2fr)]">
          <div className="space-y-4">
            {t.columns.length > 0 && (
              <section>
                <h4 className="eyebrow mb-1.5">Changes · 바뀐 컬럼</h4>
                <ul className="space-y-1 text-small">
                  {t.columns.map((c) => (
                    <li key={c.name} className="grid grid-cols-[1.25rem_minmax(0,1fr)] gap-1">
                      <span aria-hidden="true" className={cx('font-mono font-semibold', c.kind === 'added' ? 'text-ok' : c.kind === 'removed' ? 'text-danger' : 'text-warn')}>
                        {c.kind === 'added' ? '+' : c.kind === 'removed' ? '−' : '~'}
                      </span>
                      <span>
                        <span className="sr-only">{c.kind === 'added' ? '추가' : c.kind === 'removed' ? '삭제' : '수정'}: </span>
                        <span className="font-mono text-micro">{c.name}</span> <span className="text-fg-3">{c.detail}</span>
                      </span>
                    </li>
                  ))}
                </ul>
              </section>
            )}
            {t.change !== 'removed' && (
              <section>
                <h4 className="eyebrow mb-1.5">Conventions · 설계 표준</h4>
                <ul className="space-y-1 text-small">
                  {t.rules.map(({ rule, problem, severity }) => (
                    <li key={rule.id} className="grid grid-cols-[1.25rem_minmax(0,1fr)] gap-1">
                      {!problem
                        ? <CheckCircle size={16} weight="fill" className="mt-0.5 text-ok" aria-label="준수" />
                        : severity === 'ERROR'
                          ? <XCircle size={16} weight="fill" className="mt-0.5 text-danger" aria-label="위반(오류)" />
                          : <WarningOctagon size={16} weight="fill" className="mt-0.5 text-warn" aria-label="위반(경고)" />}
                      <span>
                        <span className={problem ? 'font-medium' : 'text-fg-2'}>{rule.label}</span>
                        {problem && <span className={cx('block', severity === 'ERROR' ? 'text-danger' : 'text-warn')}>{problem}</span>}
                      </span>
                    </li>
                  ))}
                </ul>
              </section>
            )}
          </div>

          <section aria-label={`${t.id} DDL`} className="min-w-0">
            <h4 className="eyebrow mb-1.5">DDL</h4>
            {t.ddl.length === 0 ? (
              <p className="text-small text-fg-3">{t.change === 'removed' ? '이 버전에서 삭제된 테이블입니다.' : 'schema.sql에서 이 테이블 문장을 찾지 못했습니다.'}</p>
            ) : (
              <pre className="relative max-h-96 overflow-auto rounded-md bg-sunken p-3 font-mono text-micro leading-relaxed">
                <code>
                  {t.ddl.join('\n\n').split('\n').map((line, i) => {
                    // 바뀐 컬럼 줄 표시: 컬럼 정의 줄은 '    이름 타입' 으로 시작한다
                    const col = /^\s{2,}"?(\w+)"?\s/.exec(line)?.[1]
                    const kind = col ? changedCols.get(col) : undefined
                    return (
                      <span key={i} className={cx('block', kind === 'added' && 'bg-ok-soft', kind === 'changed' && 'bg-warn-soft', line.trimStart().startsWith('--') && 'text-fg-3')}>
                        {kind && <span className="sr-only">{kind === 'added' ? '추가된 줄: ' : '바뀐 줄: '}</span>}
                        {line || ' '}
                      </span>
                    )
                  })}
                </code>
              </pre>
            )}
          </section>
        </div>
      )}
    </li>
  )
}
